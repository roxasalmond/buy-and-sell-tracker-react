import { describe, expect, it } from "vitest";
import { buildActivity } from "./activity";
import { computeSummary } from "./summary";
import { fundRows, installmentPlans, remitRows, soldUnits, txnNumber, unitsInStock } from "./views";
import { records } from "./testFixture";

describe("tab views", () => {
  it("splits units by status without overlap", () => {
    const stock = unitsInStock(records);
    const sold = soldUnits(records);
    expect(stock.every((u) => u.status === "in-stock")).toBe(true);
    expect(sold.every((u) => u.status === "sold")).toBe(true);
    const stockKeys = new Set(stock.map((u) => u.key));
    expect(sold.some((u) => stockKeys.has(u.key))).toBe(false);
  });

  it("lists newest first", () => {
    for (const rows of [unitsInStock(records), soldUnits(records), installmentPlans(records), remitRows(records), fundRows(records)]) {
      const nums = rows.map((r) => txnNumber(r.transactionId));
      expect(nums).toEqual([...nums].sort((a, b) => b - a));
    }
  });

  it("inventory card equals the cost of the non-deleted in-stock rows", () => {
    const cost = unitsInStock(records).reduce((t, u) => (u.deleted ? t : t + u.cost), 0);
    expect(computeSummary(records).inventory).toBeCloseTo(cost, 2);
  });
});

describe("activity feed", () => {
  it("returns at most 20 items, newest first, none generated by a sale", () => {
    const items = buildActivity(records);
    expect(items.length).toBeLessThanOrEqual(20);
    const times = items.map((a) => a.timestamp);
    expect(times).toEqual([...times].sort((a, b) => b - a));
  });
});
